export function getInitiativeBySlug(slug: string): Initiative | undefined {
  return initiatives.find((it) => it.slug === slug);
}

export function getRelatedInitiatives(current: Initiative, count = 3): Initiative[] {
  return initiatives.filter((it) => it.id !== current.id && it.displayType !== "gallery").slice(0, count);
}

export function getFeaturedInitiative(): Initiative {
  return initiatives.find((it) => it.featured) ?? initiatives[0];
}

export const galleryInitiative = initiatives.find((it) => it.displayType === "gallery")!;
export const displayableInitiatives = initiatives.filter((it) => it.displayType !== "gallery");
